# ── Framebuffer ──
buf = bytearray(W * H * 2)
fb = framebuf.FrameBuffer(buf, W, H, framebuf.RGB565)

# ── Vibrant gradient sky ──
cx, cy = 120, 120
for y in range(H):
    for x in range(W):
        dx, dy = x - cx, y - cy
        dist = math.sqrt(dx*dx + dy*dy) / 120.0
        if dist > 1.0:
            continue  # outside circle
        # Gradient based on position
        angle = math.atan2(dy, dx)
        r = int(80 + 175 * abs(math.sin(angle * 2 + dist)))
        g = int(30 + 200 * abs(math.cos(angle * 3 - dist * 2)))
        b = int(160 + 95 * math.sin(dist * 5))
        r = min(255, max(0, r))
        g = min(255, max(0, g))
        b = min(255, max(0, b))
        fb.pixel(x, y, rgb565(r, g, b))

# Stars
for _ in range(50):
    angle = random.uniform(0, math.pi * 2)
    dist = random.uniform(10, 115)
    x = int(cx + dist * math.cos(angle))
    y = int(cy + dist * math.sin(angle))
    if 0 <= x < W and 0 <= y < H:
        fb.pixel(x, y, rgb565(255, 255, 255))

# Planet/center
for r in range(28, 0, -1):
    t = r / 28.0
    cr = int(50 + 180 * (1-t))
    cg = int(80 + 100 * t)
    cb = int(220 - 100 * t)
    fb.ellipse(cx, cy, r, r, rgb565(cr, cg, cb), True)

# Text
fb.text('RAWDOG1', 50, 55, rgb565(255, 255, 255))
fb.text('PICO 2 W', 55, 75, rgb565(255, 220, 60))

# ── Push ──
def set_window(x, y, w, h):
    cmd(0x2A, x>>8, x&0xFF, (x+w-1)>>8, (x+w-1)&0xFF)
    cmd(0x2B, y>>8, y&0xFF, (y+h-1)>>8, (y+h-1)&0xFF)
    cmd(0x2C)

set_window(0, 0, W, H)
CS(0); DC(1); spi.write(buf); CS(1)
print('Artwork live!')